export function resolveDesktopLocale(value:string):DesktopLocale{
 const normalized=value.replaceAll('_','-').toLowerCase(),exact=DESKTOP_LOCALES.find(locale=>locale.toLowerCase()===normalized);if(exact)return exact;
 if(normalized.startsWith('zh-hant')||/^zh-(tw|hk|mo)(-|$)/.test(normalized))return 'zh-Hant';
 if(normalized.startsWith('zh'))return 'zh-Hans';if(normalized.startsWith('pt'))return 'pt-BR';
 const primary=normalized.split('-')[0];return DESKTOP_LOCALES.find(locale=>locale===primary)??'zh-Hans';
}
